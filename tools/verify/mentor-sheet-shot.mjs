/* 打开 A.F 详情并截图 */
const sleep = ms => new Promise(r => setTimeout(r, ms));
const fs = await import('node:fs');
const ver = await (await fetch('http://127.0.0.1:9555/json/version')).json();
const ws = new WebSocket(ver.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
const send = (m, q = {}, S) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: q, sessionId: S })); });
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const { targetId } = await send('Target.createTarget', { url: 'about:blank' });
const { sessionId: S } = await send('Target.attachToTarget', { targetId, flatten: true });
await send('Page.enable', {}, S);
await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false }, S);
await send('Page.navigate', { url: 'http://127.0.0.1:8622/index.html' }, S);
await sleep(3000);
await send('Runtime.evaluate', { expression: `(() => {
  document.getElementById('instructors-root').scrollIntoView();
  [...document.querySelectorAll('#instructors-grid .person-card')].find(c => c.dataset.mid === 'inst-aca-039').click();
  const p = document.querySelector('.mentor-sheet__panel');
  p.scrollTop = 0; return 'ok';
})()`, returnByValue: true }, S);
await sleep(800);
const shot = await send('Page.captureScreenshot', { format: 'png' }, S);
fs.writeFileSync('/tmp/mentor-sheet-af.png', Buffer.from(shot.data, 'base64'));
await send('Runtime.evaluate', { expression: `document.querySelector('.mentor-sheet__panel').scrollTop = 99999; 'ok'`, returnByValue: true }, S);
await sleep(500);
const shot2 = await send('Page.captureScreenshot', { format: 'png' }, S);
fs.writeFileSync('/tmp/mentor-sheet-af-bottom.png', Buffer.from(shot2.data, 'base64'));
console.log('截图完成');
process.exit(0);
